-- ============================================================
-- Intelligent Traffic Signal Controller
-- Oracle Database Schema
--
-- EXACTLY 5 ENTITIES:
-- 1. JUNCTION
-- 2. ROAD
-- 3. CAMERA
-- 4. VEHICLECOUNT
-- 5. SIGNAL
--
-- Emergency Priority is a PL/SQL feature.
-- It is NOT a separate entity.
-- ============================================================


-- ============================================================
-- 1. JUNCTION
-- ============================================================

CREATE TABLE JUNCTION (
    JunctionID      VARCHAR2(10) PRIMARY KEY,
    JunctionName    VARCHAR2(100) NOT NULL,
    Location        VARCHAR2(200)
);


-- ============================================================
-- 2. ROAD
-- ============================================================

CREATE TABLE ROAD (
    RoadID          VARCHAR2(10) PRIMARY KEY,
    RoadName        VARCHAR2(100) NOT NULL,
    Length          NUMBER(8,2),
    SpeedLimit      NUMBER(5,2),
    JunctionID      VARCHAR2(10) NOT NULL,
    CONSTRAINT FK_ROAD_JUNCTION
        FOREIGN KEY (JunctionID)
        REFERENCES JUNCTION(JunctionID)
);


-- ============================================================
-- 3. CAMERA
-- ============================================================

CREATE TABLE CAMERA (
    CameraID        VARCHAR2(10) PRIMARY KEY,
    RoadID          VARCHAR2(10) NOT NULL,
    Location        VARCHAR2(200),
    Status          VARCHAR2(20) DEFAULT 'ACTIVE',
    CONSTRAINT FK_CAMERA_ROAD
        FOREIGN KEY (RoadID)
        REFERENCES ROAD(RoadID),
    CONSTRAINT CK_CAMERA_STATUS
        CHECK (Status IN ('ACTIVE', 'INACTIVE', 'MAINTENANCE'))
);


-- ============================================================
-- 4. VEHICLECOUNT
-- ============================================================

CREATE TABLE VEHICLECOUNT (
    CountID         NUMBER GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
    CameraID        VARCHAR2(10) NOT NULL,
    VehicleCount    NUMBER NOT NULL,
    Timestamp       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Density         VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_VEHICLECOUNT_CAMERA
        FOREIGN KEY (CameraID)
        REFERENCES CAMERA(CameraID),
    CONSTRAINT CK_VEHICLECOUNT_VALUE
        CHECK (VehicleCount >= 0),
    CONSTRAINT CK_VEHICLECOUNT_DENSITY
        CHECK (Density IN ('LOW', 'MEDIUM', 'HIGH'))
);


-- ============================================================
-- 5. SIGNAL
-- ============================================================

CREATE TABLE SIGNAL (
    SignalID        VARCHAR2(10) PRIMARY KEY,
    JunctionID      VARCHAR2(10) NOT NULL,
    SignalStatus    VARCHAR2(20) DEFAULT 'RED',
    GreenTime       NUMBER(5) DEFAULT 20,
    RedTime         NUMBER(5) DEFAULT 60,
    CONSTRAINT FK_SIGNAL_JUNCTION
        FOREIGN KEY (JunctionID)
        REFERENCES JUNCTION(JunctionID),
    CONSTRAINT CK_SIGNAL_STATUS
        CHECK (SignalStatus IN ('RED', 'GREEN', 'YELLOW')),
    CONSTRAINT CK_SIGNAL_GREEN_TIME
        CHECK (GreenTime > 0),
    CONSTRAINT CK_SIGNAL_RED_TIME
        CHECK (RedTime > 0)
);


-- ============================================================
-- VERIFY THE FIVE TABLES
-- ============================================================

SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
    'JUNCTION',
    'ROAD',
    'CAMERA',
    'VEHICLECOUNT',
    'SIGNAL'
)
ORDER BY TABLE_NAME;


